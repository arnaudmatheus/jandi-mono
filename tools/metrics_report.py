"""Markdown presentation of the measurements, independent of rendering."""

from collections.abc import Iterable

import numpy as np

from metric_types import FontMetrics


def _table_heading(label: str, labels: Iterable[str]) -> list[str]:
    labels = list(labels)
    return [
        (f"| {label} | " if label else "| | ") + " | ".join(labels) + " |",
        "|---|" + "---|" * len(labels),
    ]


def _table_row(label: str, cells: Iterable[str]) -> str:
    return f"| {label} | " + " | ".join(cells) + " |"


def _confusability_table(
    res: dict[str, FontMetrics], px: int, pairs: list[tuple[str, str]]
) -> list[str]:
    md = [f"**{px} px**", "", *_table_heading("Pair", res)]
    for a, b in pairs:
        key = f"{a}/{b}"
        md.append(
            _table_row(
                f"`{key}`", (f"{r['confusability'][px][key]:.3f}" for r in res.values())
            )
        )
    means = (
        f"**{np.mean(list(r['confusability'][px].values())):.3f}**"
        for r in res.values()
    )
    return md + [_table_row("**mean**", means), ""]


def _spacing_table(res: dict[str, FontMetrics]) -> list[str]:
    values = [r["spacing"] for r in res.values()]
    return [
        "## Spacing evenness (bigram ink gaps at 40 px)",
        "",
        *_table_heading("", res),
        _table_row("Mean gap (px)", (str(r["mean_gap_px@40"]) for r in values)),
        _table_row(
            "Variation (CV, lower = more even)", (f"**{r['cv']}**" for r in values)
        ),
        _table_row("Tightest", (" ".join(r["tightest"]) for r in values)),
        _table_row("Loosest", (" ".join(r["loosest"]) for r in values)),
    ]


def _roman_italic_table(res: dict[str, FontMetrics]) -> list[str]:
    means = (
        f"**{r['roman_italic']['mean']}**" if "roman_italic" in r else "—"
        for r in res.values()
    )
    return [
        "",
        "## Roman / italic similarity (15 px, lower = comments read apart from code)",
        "",
        *_table_heading("", res),
        _table_row("Mean", means),
    ]


def _angle_table(res: dict[str, FontMetrics], setups: list[str]) -> list[str]:
    md = [
        "",
        "## Visual angle of the x-height at 12 pt (critical print size ≈ 0.2°)",
        "",
        *_table_heading("Setup", res),
    ]
    for name in setups:
        angles = [r["visual_angle"][name] for r in res.values()]
        md.append(
            _table_row(
                name, (f"{r['degrees']}° ({r['x_height_mm']} mm)" for r in angles)
            )
        )
    return md


def _sharpness_table(res: dict[str, FontMetrics]) -> list[str]:
    md = [
        "",
        "## Sharpness at 12 px (share of fully dark ink pixels, higher = crisper)",
        "",
        *_table_heading("Hinting", res),
    ]
    for hint in ("hintslight", "hintnone"):
        md.append(_table_row(hint, (str(r["sharpness"][hint]) for r in res.values())))
    return md


def metrics_markdown(
    res: dict[str, FontMetrics],
    sizes: list[int],
    pairs: list[tuple[str, str]],
    setups: list[str],
) -> str:
    """Keep the established report layout; e.g. ``metrics_markdown(results, [12], [("t", "r")], [])``."""
    md = _metrics_heading()
    for px in sizes:
        md += _confusability_table(res, px, pairs)
    md += _spacing_table(res) + _roman_italic_table(res)
    md += _angle_table(res, setups) + _sharpness_table(res)
    return "\n".join(md) + "\n"


def _metrics_heading() -> list[str]:
    return [
        "# Jandí Mono — metrics",
        "",
        "Generated by `tools/measure.py`. Pango/FreeType, hintslight, grayscale AA, "
        "each font in an isolated fontconfig. Similarity: 1.0 = identical (lower is better for confusable pairs).",
        "",
        "## Confusability (similarity, lower = easier to tell apart)",
        "",
    ]
